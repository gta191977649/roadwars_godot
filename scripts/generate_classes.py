"""Generate traceable, compilable class scaffolds without claiming recovered ABI or behavior."""
import argparse
from collections import defaultdict
import hashlib
import json
from pathlib import Path
import re
import sys
from tracking import ROOT, load_rows, save_rows, synchronize, validate

def snake(value):
    value = re.sub(r'([a-z0-9])([A-Z])', r'\1_\2', value)
    value = re.sub(r'[^a-zA-Z0-9]+', '_', value).strip('_').lower()
    return value or 'unnamed'

def digest(text):
    return hashlib.sha256(text.encode('utf-8')).hexdigest()

def cpp_string(value):
    return json.dumps(value, ensure_ascii=True)

def outputs(rows, layout, inventory):
    classes = {r['id']: r for r in rows if r['kind'] == 'class'}
    members = defaultdict(list)
    for row in rows:
        if row['kind'] == 'function' and row['class_id']:
            if row['class_id'] not in classes:
                raise ValueError('Unknown class owner: ' + row['class_id'])
            members[row['class_id']].append(row)
    if set(layout['classes']) - classes.keys():
        raise ValueError('Layout refers to unknown class IDs')
    signatures = {f['entry_point'].lower(): f.get('signature', '') for f in inventory['functions']}
    files, symbols = {}, {}
    for key, cls in sorted(classes.items()):
        config = layout['classes'].get(key, {})
        directory = config.get('directory', layout['default_directory'])
        if config and not config.get('evidence'):
            raise ValueError('Original source layout override needs evidence: ' + key)
        folder = Path(directory)
        if folder.is_absolute() or '..' in folder.parts or not folder.parts or folder.parts[0] != 'game_src' or '\\' in directory:
            raise ValueError('Class output must be a safe repository-relative game_src directory')
        original = cls['original_name'].removeprefix('class ').removeprefix('struct ')
        chosen = cls['recovered_name'] or original
        # An address suffix avoids collisions and distinguishes scaffold types from ABI types.
        type_name = ''.join(word[:1].upper() + word[1:] for word in re.findall(r'[A-Za-z0-9]+', chosen))
        if not type_name or type_name[0].isdigit(): type_name = 'Recovered' + type_name
        type_name += '_' + cls['address']
        stem = (folder / (snake(chosen) + '_' + cls['address'])).as_posix()
        header = ['// Generated by scripts/generate_classes.py. Hand edits are protected on regeneration.',
                  '// Scaffold type only: original layout, inheritance and ABI are not recovered.',
                  '// Original type: ' + original.replace('\n', ' '), '// Class ID: ' + key,
                  '// Path evidence: ' + config.get('evidence', 'Unknown original path; unresolved fallback.'),
                  '#pragma once', '', 'namespace roadwars::recovered {', f'class {type_name} {{', '  public:']
        source = ['// Generated scaffold. Replace RE-STUB with RE only after actual implementation.',
                  f'#include "{stem}.hpp"', '#include "game_src/core/not_implemented.hpp"', '',
                  'namespace roadwars::recovered {']
        for row in sorted(members[key], key=lambda r: r['address']):
            name = 'unresolved_' + snake(row['original_name']) + '_' + row['address']
            header += ['    // Observed signature (not a confirmed portable ABI): ' + signatures.get(row['address'], 'unknown').replace('\n', ' '),
                       f'    void {name}();']
            source += ['// RE-STUB: ' + row['id'], f'void {type_name}::{name}() {{',
                       '    not_implemented(' + cpp_string(row['id']) + ', ' + cpp_string(original + '::' + row['original_name']) + ');', '}']
            symbols[row['id']] = 'roadwars::recovered::' + type_name + '::' + name
        if not members[key]:
            header.append('    // No member functions have a confirmed registry association yet.')
        header += ['};', '} // namespace roadwars::recovered', '']
        source += ['} // namespace roadwars::recovered', '']
        for path, content in [(stem + '.hpp', '\n'.join(header)), (stem + '.cpp', '\n'.join(source))]:
            if path in files: raise ValueError('Output path collision: ' + path)
            files[path] = content
    cpp_files = sorted(path for path in files if path.endswith('.cpp'))
    files['game_src/generated_classes.cmake'] = 'set(ROADWARS_CLASS_SOURCES\n' + ''.join('  "${PROJECT_SOURCE_DIR}/' + p + '"\n' for p in cpp_files) + ')\n'
    return files, symbols

def generate(root=ROOT, check=False):
    rows = load_rows(root)
    problems = validate(rows, root)
    if problems:
        raise ValueError('\n'.join(problems))
    layout = json.loads((root / 'docs/agent/class_layout.json').read_text(encoding='utf-8'))
    inventory = json.loads((root / 'docs/agent/evidence/roadwars_inventory.json').read_text(encoding='utf-8'))
    if not rows or {r['binary_sha256'] for r in rows} != {inventory['binary_sha256']}:
        raise ValueError('Registry/export identity mismatch')
    files, symbols = outputs(rows, layout, inventory)
    manifest_path = root / 'docs/agent/class_generation.json'
    old = json.loads(manifest_path.read_text()) if manifest_path.exists() else {'files': {}}
    errors, writes = [], {}
    for path, desired in files.items():
        target = (root / path).resolve()
        if not target.is_relative_to(root.resolve()): raise ValueError('Output escapes repository')
        current = target.read_text(encoding='utf-8') if target.exists() else None
        previous = old['files'].get(path)
        if current == desired: continue
        if previous and previous == digest(desired) and current is not None:
            # Template is unchanged: preserve the user's implementation verbatim.
            continue
        if current is not None and digest(current) != previous:
            errors.append('Hand-edited/unowned file requires manual merge: ' + path)
        elif check:
            errors.append('Missing or stale generated file: ' + path)
        else:
            writes[path] = desired
    removed = old['files'].keys() - files.keys()
    if removed: errors += ['Output moved/removed; reconcile explicitly (nothing deleted): ' + p for p in sorted(removed)]
    new_manifest = {'schema_version': 1, 'files': {p: digest(c) for p, c in sorted(files.items())},
                    'class_count': sum(r['kind'] == 'class' for r in rows), 'member_count': len(symbols)}
    if check and old != new_manifest: errors.append('Class generation manifest is stale')
    if errors: raise ValueError('\n'.join(errors))
    if not check:
        for path, text in writes.items():
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(text, encoding='utf-8', newline='\n')
        manifest_path.write_text(json.dumps(new_manifest, indent=2) + '\n', encoding='utf-8')
        for row in rows:
            if row['id'] in symbols and not row['source_symbol']:
                row['source_symbol'] = symbols[row['id']]
            if row['kind'] == 'class':
                row['source_path'] = next(path for path, text in files.items()
                                          if path.endswith('.hpp') and '// Class ID: ' + row['id'] + '\n' in text)
        synchronize(rows, root)
        errors = validate(rows, root)
        if errors: raise ValueError('\n'.join(errors))
        save_rows(rows, root)
    print(f'Class scaffolds: {new_manifest["class_count"]} types, {len(symbols)} associated members; {len(writes)} files written')

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        generate(args.root, args.check)
    except (ValueError, KeyError, OSError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
