Result FrontendLocalization::load(ResourceStore& resources, std::string_view table,
                                  std::string& error) {
    if (table.empty() || table.size() > 128 ||
        !std::all_of(table.begin(), table.end(), [](unsigned char c) {
            return (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || (c >= '0' && c <= '9') ||
                   c == '_' || c == ' ';
        })) {
        error = "Invalid localization table name";
        return Result::invalid_argument;
    }
    std::vector<std::byte> bytes;
    const auto path = "Localization/" + std::string(table) + ".bin";
    const auto result = resources.read(path, bytes);
    if (result != Result::ok) {
        error = "Cannot read " + path;
        return result;
    }
    return decode(bytes, error);
}

// RE: 93b4e4c301a5694b55e16977c2e52f4971bd9089659e3d58617c8af2368436c8:function:0045f847
// The portable table path omits the original destructive TXT-to-BIN conversion and Win32 UI.
Result FrontendLocalization::decode(std::span<const std::byte> encoded, std::string& error) {
    constexpr std::size_t kMaxBytes = 8 * 1024 * 1024;
    constexpr std::size_t kMaxRows = 65536;
    constexpr std::size_t kMaxField = 511;
    constexpr std::size_t kMaxLanguages = 32;
    const auto fail = [&]() {
        error = "Malformed or oversized localization table";
        return Result::invalid_argument;
    };
    if (encoded.empty() || encoded.size() > kMaxBytes)
        return fail();
    decltype(records_) records;
    std::vector<std::string> fields;
    std::string field;
    const auto finish_field = [&]() {
        if (fields.size() == kMaxLanguages)
            return false;
        fields.push_back(std::move(field));
        field.clear();
        return true;
    };
    const auto finish_row = [&]() {
        if (!finish_field() || fields.size() < 2 || fields.front().empty() ||
            records.size() == kMaxRows)
            return false;
        // The original scans forward and accepts the first matching case-sensitive key.
        const auto key = fields.front();
        records.try_emplace(key, std::move(fields));
        fields.clear();
        return true;
    };
    for (const auto byte : encoded) {
        const auto value = static_cast<unsigned char>((std::to_integer<unsigned>(byte) + 1) & 255);
        if (!value)
            return fail();
        if (value == '\t') {
            if (!finish_field())
                return fail();
        } else if (value == '\n') {
            if (!finish_row())
                return fail();
        } else if (value != '"') {
            if (field.size() == kMaxField)
                return fail();
            field.push_back(static_cast<char>(value));
        }
    }
    // Original data has LF-delimited records. A bounded final record is accepted at EOF.
    if ((!fields.empty() || !field.empty()) && !finish_row())
        return fail();
    if (records.empty())
        return fail();
    records_ = std::move(records);
    error.clear();
    return Result::ok;
}

Result FrontendLocalization::lookup(std::string_view key, int language, std::string& output) const {
    output = key;
    if (language < 0 || language >= 32)
        return Result::invalid_argument;
    if (language == 0)
        return Result::ok;
    const auto found = records_.find(key);
    if (found == records_.end() || static_cast<std::size_t>(language) >= found->second.size())
        return Result::not_found;
    // 0045fc03 resets only the write index: an empty column retains the previous output.
    // A quoted empty field likewise writes no bytes. Keep this observed carry-forward behavior.
    for (int index = 1; index <= language; ++index) {
        const auto& translation = found->second[static_cast<std::size_t>(index)];
        if (!translation.empty())
            output = translation;
    }
    return Result::ok;
}

