#include "game_src/unresolved/weapon_trails.hpp"
#include <cassert>
#include <cmath>
using namespace roadwars;
int main() {
    std::uint32_t draws{};
    ParticleRandom borrowed([&] {
        ++draws;
        return 9u;
    });
    assert(borrowed.next() == 9 && draws == 1);
    draws = 0;
    WeaponTrailPool plasma;
    assert(plasma.configure("Plasma Blaster", .5f) == Result::ok);
    assert(plasma.particles().size() == 50);
    assert(plasma.advance(.03f, true, {3, 4, 5}, {10, 20, 30}, borrowed) == Result::ok);
    assert(plasma.active_count() == 1 && draws == 3);
    assert(plasma.particles()[0].atlas_frame == 2);
    assert(plasma.particles()[0].size == 1);
    assert(plasma.advance(1, false, {}, {}, borrowed) == Result::ok);
    assert(plasma.active_count() == 0);
    assert(draws == 3);
    WeaponTrailPool rocket;
    assert(rocket.configure("Rocket Launcher", 0) == Result::ok);
    assert(rocket.particles().size() == 200);
    assert(rocket.advance(0, true, {}, {}, borrowed) == Result::ok);
    assert(rocket.active_count() == 0);
    assert(rocket.advance(.01f, true, {0, 5, 20}, {}, borrowed) == Result::ok);
    assert(rocket.active_count() == 3 && draws == 6);
    assert(rocket.draw_order()[0] == 2 && rocket.draw_order()[2] == 0);
    assert(std::abs(rocket.particles()[0].position.z - 20.f / 3) < .001f);
    assert(rocket.particles()[2].position.z == 20);
    assert(rocket.particles()[0].atlas_frame == 9);
    std::uint32_t frame{};
    assert(rocket.atlas_frame(0, frame) == Result::unavailable);
    const auto position = rocket.particles()[0].position;
    assert(rocket.advance(.18f, false, {100, 100, 100}, {}, borrowed) == Result::ok);
    assert(rocket.particles()[0].atlas_frame == 0);
    assert(rocket.atlas_frame(0, frame) == Result::ok && frame == 0);
    assert(rocket.particles()[0].position.z == position.z);
    assert(rocket.advance(2, false, {}, {}, borrowed) == Result::ok);
    assert(rocket.active_count() == 0 && draws == 6);
    rocket.reset();
    assert(rocket.advance(0, true, {}, {}, borrowed) == Result::ok);
    // Vertical-only movement consumes no emission-distance threshold.
    assert(rocket.advance(.1f, true, {0, 50, 0}, {}, borrowed) == Result::ok);
    assert(rocket.active_count() == 0);
    assert(rocket.advance(.01f, true, {2, 50, 0}, {}, borrowed) == Result::ok);
    assert(rocket.active_count() == 1);
    // Reused slot's UV survives a new raw random frame outside0..3.
    assert(rocket.atlas_frame(0, frame) == Result::ok && frame == 0);
    assert(rocket.configure("Machine Gun", 1) == Result::unavailable);
    assert(rocket.advance(-1, true, {}, {}, borrowed) == Result::invalid_argument);
    WeaponTrailPool guided;
    assert(guided.configure("The Excalibur", 1) == Result::ok);
    draws = 0;
    assert(guided.particles().size() == 150);
    assert(guided.advance(.03f, true, {}, {}, borrowed) == Result::ok);
    assert(draws == 4 && guided.active_count() == 1);
    assert(guided.particles()[0].atlas_frame == 1 && guided.particles()[0].size == 3);
    assert(std::abs(guided.particles()[0].remaining_life - .9775f) < .0001f);
    assert(guided.configure("Swarmers", 1) == Result::ok);
    draws = 0;
    assert(guided.advance(.03f, true, {}, {}, borrowed) == Result::ok);
    assert(draws == 3 && guided.particles()[0].atlas_frame == 1);
    assert(guided.configure("Nitrous Boost", 1) == Result::ok);
    assert(guided.advance(.03f, true, {}, {}, borrowed) == Result::ok);
    assert(guided.particles()[0].atlas_frame == 3 && guided.particles()[0].size == 3);
    assert(guided.configure("Electron Cannon", 1) == Result::ok);
    assert(guided.advance(.03f, true, {}, {}, borrowed) == Result::ok);
    assert(guided.particles()[0].atlas_frame == 0);
    assert(std::abs(guided.particles()[0].remaining_life - .955f) < .0001f);
    WeaponTrailPool screen;
    assert(screen.configure("Smoke Screen", 0) == Result::ok);
    assert(screen.particles().size() == 20);
    draws = 0;
    assert(screen.advance(.19f, true, {}, {}, borrowed, 0) == Result::ok);
    assert(screen.active_count() == 0);
    assert(screen.advance(.02f, true, {}, {}, borrowed, 0) == Result::ok);
    assert(screen.active_count() == 1 && draws == 2);
    assert(screen.particles()[0].atlas_frame == 9);
    assert(screen.atlas_frame(0, frame) == Result::unavailable);
    assert(std::abs(screen.particles()[0].remaining_life - 1.996f) < .0001f);
    assert(screen.particles()[0].velocity.x < -.33f);
    assert(std::abs(screen.particles()[0].velocity.y - .09f) < .0001f);
    assert(std::abs(screen.screen_triangles()[0][2].x - 1.11f) < .0001f);
    assert(screen.advance(.5f, true, {}, {}, borrowed, 0) == Result::ok);
    assert(screen.active_count() == 2 && draws == 4);
    assert(screen.draw_order()[0] == 1 && screen.particles()[1].velocity.x > .33f);
    assert(screen.atlas_frame(0, frame) == Result::ok && frame == 0);
    assert(screen.advance(11, false, {}, {}, borrowed, 0) == Result::ok);
    assert(screen.active_count() == 0);
    WeaponImpactPool burst;
    assert(burst.configure("Machine Gun", 1) == Result::ok);
    assert(burst.settings().capacity == 15 && burst.settings().size == .25f);
    assert(burst.begin({{2, 3, 4}, {5, 6, 7}, 2}));
    assert(!burst.begin({}));
    draws = 0;
    assert(burst.advance(.01f, borrowed) == Result::ok);
    assert(draws == 3 && burst.particles()[0].atlas_frame == 1);
    assert(std::abs(burst.particles()[0].remaining_life - .98f) < .0001f);
    assert(burst.configure("Guided Missile", 1, 4) == Result::ok);
    assert(burst.settings().capacity == 37 && burst.settings().atlas_choice == -2);
    assert(burst.configure("The Excalibur", .5f, 4) == Result::ok);
    assert(burst.settings().capacity == 18 && burst.settings().size == 8);
    assert(burst.configure("Vulcanized Gun", 1) == Result::ok && burst.requires_secondary_sprite());
    assert(burst.configure("Rocket Launcher", 1) == Result::ok);
    assert(burst.settings().capacity == 150 && !burst.requires_secondary_sprite());
    WeaponRearBlastPool rear;
    draws = 0;
    assert(rear.configure("Grenades", borrowed) == Result::ok && draws == 0);
    auto launched = rear.begin({1, 2, 3});
    assert(launched.primary && !launched.secondary);
    assert(!rear.begin({}).primary);
    assert(rear.advance_primary(.02f, borrowed) == Result::ok);
    assert(draws == 6 && rear.primary_order().size() == 1);
    assert(std::abs(rear.primary_particles()[0].velocity.x - (-6.1f)) < .001f);
    assert(std::abs(rear.primary_particles()[0].remaining_life - .96f) < .0001f);
    for (int index = 0; index < 120; ++index)
        assert(rear.advance_primary(1.f / 60, borrowed) == Result::ok);
    assert(!rear.primary_active() && rear.primary_order().empty());
    draws = 0;
    assert(rear.configure("Reactive Mines", borrowed) == Result::ok && draws == 10);
    launched = rear.begin({});
    assert(launched.primary && launched.secondary);
    assert(rear.advance_secondary(.1f, borrowed) == Result::ok && draws == 10);
    assert(rear.secondary_order().size() == 10 && rear.secondary_order()[0] == 9);
    assert(std::abs(rear.secondary_particles()[0].position.z - .1f) < .0001f);
    assert(rear.advance_secondary(.01f, borrowed) == Result::ok && draws == 20);
    const auto radial_z = rear.secondary_particles()[0].position.z;
    assert(rear.advance_secondary(1.5f, borrowed) == Result::ok);
    assert(std::abs(rear.secondary_particles()[0].position.z - radial_z - .15f) < .0001f);
    assert(rear.advance_secondary(11, borrowed) == Result::ok && !rear.secondary_active());
    VulcanImpactSprite sprite;
    assert(sprite.begin({}, {10, 0, 0}));
    assert(!sprite.begin({}, {}));
    assert(sprite.advance(.1f) == Result::ok);
    assert(std::abs(sprite.particle().position.x - .6f) < .0001f);
    assert(sprite.particle().size == 18 && sprite.particle().active);
    assert(sprite.advance(.15f) == Result::ok);
    assert(sprite.particle().active && std::abs(sprite.particle().position.x - .9f) < .0001f);
    assert(sprite.advance(.01f) == Result::ok && !sprite.particle().active);
}
